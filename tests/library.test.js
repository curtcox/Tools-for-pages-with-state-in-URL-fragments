import { test } from 'node:test';
import assert from 'node:assert/strict';
import { openLibrary, memoryBackend, computeCID, LIBRARY_LIMITS, suggestName } from '../src/index.js';

const config = { storagePrefix: 'test-app', maxBytes: 5 * 1024 * 1024 };
const type = { type: 'notes', normalize: value => ({ src: String(value.src), theme: value.theme ?? 'paper' }) };
const open = (options = {}) => openLibrary({ config, type, backend: options.backend ?? memoryBackend(), channel: null, now: () => Date.parse('2026-11-19T12:00:00Z'), ...options });

test('unnamed saves get unique autogenerated names; explicit names are unique ignoring case', async () => {
  const library = await open();
  const first = await library.saveAs({ doc: { src: '\n  Shopping   list\nmilk' } });
  const second = await library.saveAs({ doc: { src: 'Shopping list\neggs' } });
  const blank = await library.saveAs({ doc: { src: '   ' } });
  assert.deepEqual([first.entry.name, second.entry.name, blank.entry.name], ['Shopping list', 'Shopping list 2', 'Untitled']);
  assert.equal(first.entry.nameGenerated, true);
  assert.equal(suggestName({ src: 'x'.repeat(200) }).length, LIBRARY_LIMITS.generatedName);
  const named = await library.saveAs({ doc: { src: 'a' }, name: '  Plan\u202e A ', description: 'Line one\r\nLine two\u200b' });
  assert.deepEqual([named.entry.name, named.entry.description, named.entry.nameGenerated], ['Plan A', 'Line one\nLine two', false]);
  await assert.rejects(library.saveAs({ doc: { src: 'b' }, name: 'plan a' }), error => error.code === 'exists' && error.entry.id === named.entry.id);
  await assert.rejects(library.saveAs({ doc: { src: 'b' }, name: 'n'.repeat(LIBRARY_LIMITS.name + 1) }), /at most/);
  assert.equal((await library.entries()).length, 4);
});

test('save appends revisions with parent links, skips unchanged content and detects moved heads', async () => {
  const library = await open();
  const { entry, revision: one } = await library.saveAs({ doc: { src: 'v1' }, name: 'Doc' });
  const two = await library.save({ entry: entry.id, doc: { src: 'v2' }, expectedHead: one.id });
  assert.equal(two.revision.parent, one.id);
  const same = await library.save({ entry: entry.id, doc: { src: 'v2' } });
  assert.equal(same.unchanged, true); assert.equal(same.revision.id, two.revision.id);
  await assert.rejects(library.save({ entry: entry.id, doc: { src: 'stale tab' }, expectedHead: one.id }), error => error.code === 'conflict');
  const branch = await library.save({ entry: entry.id, doc: { src: 'from v1' }, parent: one.id });
  const history = await library.history(entry.id);
  assert.deepEqual(history.map(row => [row.id, row.head]), [[branch.revision.id, true], [two.revision.id, false], [one.id, false]]);
  assert.equal(branch.revision.parent, one.id);
  assert.deepEqual((await library.load(one.id)).doc, { src: 'v1', theme: 'paper' });
  assert.equal((await library.entries())[0].count, 3);
  await assert.rejects(library.save({ entry: 'missing', doc: { src: 'x' } }), error => error.code === 'missing');
});

test('revision CIDs equal the bytes HashBin would publish, are verified on read and marked published', async () => {
  const backend = memoryBackend(), library = await open({ backend });
  const { revision } = await library.saveAs({ doc: { src: 'publish me' } });
  const payload = library.documents.serialize({ src: 'publish me' });
  assert.equal(revision.cid, await computeCID(payload));
  assert.equal(await library.cid({ src: 'publish me' }), revision.cid);
  assert.equal(await library.markPublished(revision.cid), 1);
  assert.ok((await library.load(revision.id)).revision.publishedAt);
  backend.data.get('blobs').get(revision.cid).text = payload.replace('publish', 'tampered');
  await assert.rejects(library.load(revision.id), error => error.code === 'damaged');
});

test('renaming, clearing names and descriptions does not create revisions', async () => {
  const library = await open();
  const { entry } = await library.saveAs({ doc: { src: 'Title line\nbody' }, name: 'Custom' });
  await library.saveAs({ doc: { src: 'other' }, name: 'Taken' });
  await assert.rejects(library.update(entry.id, { name: 'TAKEN' }), error => error.code === 'exists');
  assert.equal((await library.update(entry.id, { name: 'custom' })).name, 'custom');
  const cleared = await library.update(entry.id, { name: '', description: 'About' });
  assert.deepEqual([cleared.name, cleared.nameGenerated, cleared.description], ['Title line', true, 'About']);
  assert.equal((await library.history(entry.id)).length, 1);
});

test('deleting revisions reparents children and collects only unreferenced contents', async () => {
  const backend = memoryBackend(), library = await open({ backend });
  const { entry, revision: one } = await library.saveAs({ doc: { src: 'shared' } });
  const two = await library.save({ entry: entry.id, doc: { src: 'middle' } });
  const three = await library.save({ entry: entry.id, doc: { src: 'last' } });
  const other = await library.saveAs({ doc: { src: 'shared' }, name: 'Other' });
  await assert.rejects(library.removeRevision(three.revision.id), /current revision/);
  await library.removeRevision(two.revision.id);
  assert.equal((await library.history(entry.id)).find(row => row.id === three.revision.id).parent, one.id);
  assert.equal(backend.data.get('blobs').has(two.revision.cid), false);
  await library.remove(entry.id);
  assert.equal(backend.data.get('blobs').has(one.cid), true, 'still used by Other');
  assert.equal(backend.data.get('blobs').has(three.revision.cid), false);
  await library.remove(other.entry.id);
  assert.equal(backend.data.get('blobs').size, 0);
});

test('explicit loads are recorded once per content, capped, matched to revisions and clearable', async () => {
  const backend = memoryBackend(), library = await open({ backend });
  const { entry, revision } = await library.saveAs({ doc: { src: 'known' }, name: 'Known' });
  const recorded = await library.record({ src: 'known' }, { kind: 'cid', cid: revision.cid });
  assert.deepEqual(recorded.matches.map(match => [match.entry.id, match.revision.id]), [[entry.id, revision.id]]);
  await library.record({ src: 'known' }, { kind: 'link' });
  for (let i = 0; i < LIBRARY_LIMITS.recent + 5; i++) await library.record({ src: `opened ${i}` });
  const recent = await library.recent();
  assert.equal(recent.length, LIBRARY_LIMITS.recent);
  assert.equal(recent[0].matches.length, 0);
  assert.ok(!recent.some(row => row.cid === revision.cid), 'oldest entries expire');
  assert.deepEqual((await library.openRecent(recent[0].id)).doc.src, `opened ${LIBRARY_LIMITS.recent + 4}`);
  await library.clearRecent();
  assert.equal((await library.recent()).length, 0);
  assert.deepEqual([...backend.data.get('blobs').keys()], [revision.cid]);
});

test('storage failures abort the whole save and are reported without losing earlier work', async () => {
  const inner = memoryBackend(); let full = false;
  const backend = { data: inner.data, async open(schema) {
    const db = await inner.open(schema);
    return { ...db, transaction: (stores, mode, work) => db.transaction(stores, mode, ops => work({ ...ops,
      put: (store, value) => full && store === 'revisions' ? Promise.reject(new DOMException('full', 'QuotaExceededError')) : ops.put(store, value) })) };
  } };
  const library = await open({ backend });
  const { entry } = await library.saveAs({ doc: { src: 'kept' }, name: 'Kept' });
  full = true;
  await assert.rejects(library.save({ entry: entry.id, doc: { src: 'lost' } }), error => error.code === 'quota');
  await assert.rejects(library.saveAs({ doc: { src: 'new' }, name: 'New' }), error => error.code === 'quota');
  full = false;
  assert.deepEqual((await library.entries()).map(row => row.name), ['Kept']);
  assert.equal(inner.data.get('blobs').size, 1);
});

test('changes notify local subscribers and other tabs through the channel', async () => {
  const backend = memoryBackend(), a = new EventTarget(), b = new EventTarget();
  const pair = (self, other) => ({ set onmessage(fn) { self.onmessage = fn; }, postMessage(data) { other.onmessage?.({ data }); }, close() {} });
  const first = await open({ backend, channel: pair(a, b) }), second = await open({ backend, channel: pair(b, a) });
  let local = 0, remote = 0; first.subscribe(() => local++); second.subscribe(() => remote++);
  await first.saveAs({ doc: { src: 'hi' } });
  assert.deepEqual([local, remote], [1, 1]);
  first.close(); second.close();
});
